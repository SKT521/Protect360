CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.CUSTOMER(
    CUSTOMER_SK, CUSTOMER_ID, FULL_NAME, AGE, AGE_BAND, DATE_OF_BIRTH,
    GENDER, STATE_CODE, POSTCODE, SEGMENT_TYPE, STATUS,
    MARKETING_CONSENT_FLAG, HEALTH_DATA_CONSENT_FLAG,
    CUSTOMER_SINCE_DATE, CURRENT_RECORD_FLAG, SOURCE_SYSTEM_CODE,
    INGESTION_TS, SILVER_UPDATED_AT, CREATED_TS
)
TARGET_LAG = '1 hour'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    MD5(RAW_PAYLOAD:customer_id::STRING) AS CUSTOMER_SK,
    RAW_PAYLOAD:customer_id::STRING AS CUSTOMER_ID,
    RAW_PAYLOAD:full_name::STRING AS FULL_NAME,
    RAW_PAYLOAD:age::NUMBER AS AGE,
    CASE
        WHEN RAW_PAYLOAD:age::NUMBER < 30 THEN 'Under 30'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 30 AND 44 THEN '30-44'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 45 AND 54 THEN '45-54'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 55 AND 59 THEN '55-59'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 60 AND 64 THEN '60-64'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 65 AND 69 THEN '65-69'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 70 AND 74 THEN '70-74'
        WHEN RAW_PAYLOAD:age::NUMBER BETWEEN 75 AND 79 THEN '75-79'
        WHEN RAW_PAYLOAD:age::NUMBER >= 80 THEN '80+'
        ELSE 'Unknown'
    END AS AGE_BAND,
    RAW_PAYLOAD:date_of_birth::DATE AS DATE_OF_BIRTH,
    RAW_PAYLOAD:gender::STRING AS GENDER,
    RAW_PAYLOAD:state_code::STRING AS STATE_CODE,
    RAW_PAYLOAD:postcode::STRING AS POSTCODE,
    COALESCE(RAW_PAYLOAD:segment_type::STRING, 'SENIOR_CITIZEN') AS SEGMENT_TYPE,
    RAW_PAYLOAD:status::STRING AS STATUS,
    RAW_PAYLOAD:marketing_consent_flag::BOOLEAN AS MARKETING_CONSENT_FLAG,
    RAW_PAYLOAD:health_data_consent_flag::BOOLEAN AS HEALTH_DATA_CONSENT_FLAG,
    RAW_PAYLOAD:customer_since_date::DATE AS CUSTOMER_SINCE_DATE,
    TRUE AS CURRENT_RECORD_FLAG,
    SOURCE_SYSTEM_CODE,
    INGESTION_TS,
    CURRENT_TIMESTAMP() AS SILVER_UPDATED_AT,
    CURRENT_TIMESTAMP() AS CREATED_TS
FROM PROTECT360_DB.BRONZE.CUSTOMER_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RAW_PAYLOAD:customer_id::STRING
    ORDER BY INGESTION_TS DESC
) = 1;


CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.CUSTOMER_FINANCIAL_PROFILE(
    FINANCIAL_SK, CUSTOMER_ID, INCOME_BAND, ASSET_BAND,
    ITR_FILING_FLAG, PENSION_INCOME_FLAG, TDS_INDICATOR,
    PMJAY_INCOME_ELIGIBLE, EMPLOYMENT_TYPE_CODE, INCOME_FREQUENCY,
    CAPACITY_SCORE, DATA_AVAILABLE_FLAG, CURRENT_RECORD_FLAG,
    INGESTION_TS, SILVER_UPDATED_AT
)
TARGET_LAG = '1 hour'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    MD5(RAW_PAYLOAD:customer_id::STRING) AS FINANCIAL_SK,
    RAW_PAYLOAD:customer_id::STRING AS CUSTOMER_ID,
    RAW_PAYLOAD:income_band::STRING AS INCOME_BAND,
    RAW_PAYLOAD:asset_band::STRING AS ASSET_BAND,
    COALESCE(RAW_PAYLOAD:itr_filing_flag::BOOLEAN, FALSE) AS ITR_FILING_FLAG,
    COALESCE(RAW_PAYLOAD:pension_income_flag::BOOLEAN, FALSE) AS PENSION_INCOME_FLAG,
    COALESCE(RAW_PAYLOAD:tds_indicator::BOOLEAN, FALSE) AS TDS_INDICATOR,
    (RAW_PAYLOAD:income_band::STRING IN ('BELOW_1L', '1L_3L'))::BOOLEAN AS PMJAY_INCOME_ELIGIBLE,
    RAW_PAYLOAD:employment_type_code::STRING AS EMPLOYMENT_TYPE_CODE,
    RAW_PAYLOAD:income_frequency::STRING AS INCOME_FREQUENCY,
    (
        CASE RAW_PAYLOAD:income_band::STRING
            WHEN 'BELOW_1L' THEN 1 WHEN '1L_3L' THEN 2
            WHEN '3L_5L' THEN 4 WHEN '5L_10L' THEN 6
            WHEN 'ABOVE_10L' THEN 9 ELSE 3
        END
        + CASE RAW_PAYLOAD:asset_band::STRING
            WHEN 'BELOW_1L' THEN 0 WHEN '1L_5L' THEN 1
            WHEN '5L_20L' THEN 1 WHEN 'ABOVE_20L' THEN 2 ELSE 1
        END
    )::NUMBER(3,1) AS CAPACITY_SCORE,
    (RAW_PAYLOAD:data_available::BOOLEAN) AS DATA_AVAILABLE_FLAG,
    TRUE AS CURRENT_RECORD_FLAG,
    INGESTION_TS,
    CURRENT_TIMESTAMP() AS SILVER_UPDATED_AT
FROM PROTECT360_DB.BRONZE.FINANCIAL_PROFILE_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RAW_PAYLOAD:customer_id::STRING
    ORDER BY INGESTION_TS DESC
) = 1;


CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.CLAIM(
    CLAIM_SK, CLAIM_ID, CUSTOMER_ID, CLAIM_DATE, CLAIM_TYPE,
    DIAGNOSIS_CODE, CLAIM_AMOUNT, CLAIM_STATUS,
    HIGH_SEVERITY_FLAG, HOSPITALIZATION_FLAG, CHRONIC_CONDITION_FLAG,
    CLAIM_IN_LAST_1Y, CLAIM_IN_LAST_3Y, INGESTION_TS, SILVER_UPDATED_AT
)
TARGET_LAG = '1 hour'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    MD5(RAW_PAYLOAD:claim_id::STRING) AS CLAIM_SK,
    RAW_PAYLOAD:claim_id::STRING AS CLAIM_ID,
    RAW_PAYLOAD:customer_id::STRING AS CUSTOMER_ID,
    RAW_PAYLOAD:claim_date::DATE AS CLAIM_DATE,
    RAW_PAYLOAD:claim_type::STRING AS CLAIM_TYPE,
    RAW_PAYLOAD:diagnosis_code::STRING AS DIAGNOSIS_CODE,
    RAW_PAYLOAD:claim_amount::NUMBER(12,2) AS CLAIM_AMOUNT,
    RAW_PAYLOAD:claim_status::STRING AS CLAIM_STATUS,
    COALESCE(RAW_PAYLOAD:high_severity_flag::BOOLEAN, FALSE) AS HIGH_SEVERITY_FLAG,
    COALESCE(RAW_PAYLOAD:hospitalization_flag::BOOLEAN, FALSE) AS HOSPITALIZATION_FLAG,
    (RAW_PAYLOAD:diagnosis_code::STRING IN ('E11','N18','I10','J44'))::BOOLEAN AS CHRONIC_CONDITION_FLAG,
    (DATEDIFF('day', RAW_PAYLOAD:claim_date::DATE, CURRENT_DATE()) <= 365)::BOOLEAN AS CLAIM_IN_LAST_1Y,
    (DATEDIFF('day', RAW_PAYLOAD:claim_date::DATE, CURRENT_DATE()) <= 365*3)::BOOLEAN AS CLAIM_IN_LAST_3Y,
    INGESTION_TS,
    CURRENT_TIMESTAMP() AS SILVER_UPDATED_AT
FROM PROTECT360_DB.BRONZE.CLAIM_RAW
WHERE RAW_PAYLOAD:claim_status::STRING != 'REJECTED'
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RAW_PAYLOAD:claim_id::STRING
    ORDER BY INGESTION_TS DESC
) = 1;


CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.CLAIM_SUMMARY(
    CUSTOMER_ID, CLAIM_COUNT_3Y, CLAIM_AMOUNT_3Y,
    HIGH_SEVERITY_CLAIM_FLAG, HOSPITALIZATION_COUNT_3Y, ICU_STAY_FLAG,
    LAST_CLAIM_DATE, LAST_ADMISSION_DATE, CHRONIC_CONDITION_CLAIM_FLAG,
    HAS_READMISSION_FLAG, OOP_BURDEN_INR, LAST_UPDATED
)
TARGET_LAG = '2 hours'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    c.CUSTOMER_ID,
    COUNT(c.CLAIM_ID) AS CLAIM_COUNT_3Y,
    SUM(c.CLAIM_AMOUNT) AS CLAIM_AMOUNT_3Y,
    BOOLOR_AGG(c.HIGH_SEVERITY_FLAG) AS HIGH_SEVERITY_CLAIM_FLAG,
    COUNT(h.HOSPITALIZATION_ID) AS HOSPITALIZATION_COUNT_3Y,
    BOOLOR_AGG(h.ICU_STAY_FLAG) AS ICU_STAY_FLAG,
    MAX(c.CLAIM_DATE) AS LAST_CLAIM_DATE,
    MAX(h.ADMISSION_DATE) AS LAST_ADMISSION_DATE,
    BOOLOR_AGG(c.CHRONIC_CONDITION_FLAG) AS CHRONIC_CONDITION_CLAIM_FLAG,
    BOOLOR_AGG(h.READMISSION_30D_FLAG) AS HAS_READMISSION_FLAG,
    COALESCE(SUM(h.TOTAL_BILLED_INR - h.INSURANCE_COVERED_INR), 0) AS OOP_BURDEN_INR,
    CURRENT_TIMESTAMP() AS LAST_UPDATED
FROM PROTECT360_DB.SILVER.CLAIM c
LEFT JOIN PROTECT360_DB.SILVER.HOSPITALIZATION h
    ON c.CUSTOMER_ID = h.CUSTOMER_ID AND h.IN_LAST_3Y = TRUE
WHERE c.CLAIM_IN_LAST_3Y = TRUE
GROUP BY c.CUSTOMER_ID;


