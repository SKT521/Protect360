CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.SURVEY_RESPONSE(
    SURVEY_SK, SURVEY_ID, CUSTOMER_ID, SUBMITTED_BY,
    HEALTH_CONDITIONS_RAW, HAS_DIABETES, HAS_HYPERTENSION,
    HAS_HEART_DISEASE, HAS_COPD, HAS_ARTHRITIS, HAS_ANY_CONDITION,
    CONDITION_COUNT, CURRENT_COVERAGE_STATUS, IS_UNINSURED,
    LIVING_SITUATION, LIVING_ALONE_FLAG, IN_CARE_HOME_FLAG,
    PREFERRED_SERVICES_RAW, WANTS_TELEMEDICINE, WANTS_HOME_VISIT,
    WANTS_ELDER_CARE, WANTS_FINANCIAL_ADVICE, WANTS_CHECKUP,
    SURVEY_SUBMITTED_DATE, INGESTION_TS, SILVER_UPDATED_AT
)
TARGET_LAG = '1 hour'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    MD5(RAW_PAYLOAD:survey_id::STRING) AS SURVEY_SK,
    RAW_PAYLOAD:survey_id::STRING AS SURVEY_ID,
    RAW_PAYLOAD:customer_id::STRING AS CUSTOMER_ID,
    RAW_PAYLOAD:submitted_by::STRING AS SUBMITTED_BY,
    RAW_PAYLOAD:health_conditions::STRING AS HEALTH_CONDITIONS_RAW,
    CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'diabetes') AS HAS_DIABETES,
    CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'hypertension') AS HAS_HYPERTENSION,
    CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'heart_disease') AS HAS_HEART_DISEASE,
    CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'copd') AS HAS_COPD,
    CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'arthritis') AS HAS_ARTHRITIS,
    NOT CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'none_of_above')
        AND RAW_PAYLOAD:health_conditions::STRING IS NOT NULL AS HAS_ANY_CONDITION,
    (
        IFF(CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'diabetes'), 1, 0) +
        IFF(CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'hypertension'), 1, 0) +
        IFF(CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'heart_disease'), 1, 0) +
        IFF(CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'copd'), 1, 0) +
        IFF(CONTAINS(RAW_PAYLOAD:health_conditions::STRING, 'arthritis'), 1, 0)
    ) AS CONDITION_COUNT,
    RAW_PAYLOAD:current_coverage::STRING AS CURRENT_COVERAGE_STATUS,
    (RAW_PAYLOAD:current_coverage::STRING = 'none')::BOOLEAN AS IS_UNINSURED,
    RAW_PAYLOAD:living_situation::STRING AS LIVING_SITUATION,
    (RAW_PAYLOAD:living_situation::STRING = 'alone')::BOOLEAN AS LIVING_ALONE_FLAG,
    (RAW_PAYLOAD:living_situation::STRING = 'care_home')::BOOLEAN AS IN_CARE_HOME_FLAG,
    RAW_PAYLOAD:preferred_services::STRING AS PREFERRED_SERVICES_RAW,
    CONTAINS(RAW_PAYLOAD:preferred_services::STRING, 'telemedicine') AS WANTS_TELEMEDICINE,
    CONTAINS(RAW_PAYLOAD:preferred_services::STRING, 'home_visit') AS WANTS_HOME_VISIT,
    CONTAINS(RAW_PAYLOAD:preferred_services::STRING, 'elder_care') AS WANTS_ELDER_CARE,
    CONTAINS(RAW_PAYLOAD:preferred_services::STRING, 'financial_advice') AS WANTS_FINANCIAL_ADVICE,
    CONTAINS(RAW_PAYLOAD:preferred_services::STRING, 'checkup') AS WANTS_CHECKUP,
    RAW_PAYLOAD:submitted_ts::DATE AS SURVEY_SUBMITTED_DATE,
    INGESTION_TS,
    CURRENT_TIMESTAMP() AS SILVER_UPDATED_AT
FROM PROTECT360_DB.BRONZE.SURVEY_RESPONSE_RAW
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RAW_PAYLOAD:customer_id::STRING
    ORDER BY INGESTION_TS DESC
) = 1;


CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.SURVEY_SUMMARY(
    CUSTOMER_ID, SURVEY_ID, SUBMITTED_BY,
    CONDITION_COUNT, HAS_DIABETES, HAS_HYPERTENSION, HAS_HEART_DISEASE,
    HAS_COPD, HAS_ARTHRITIS, HAS_ANY_CONDITION,
    CURRENT_COVERAGE_STATUS, IS_UNINSURED,
    LIVING_SITUATION, LIVING_ALONE_FLAG, IN_CARE_HOME_FLAG,
    WANTS_TELEMEDICINE, WANTS_HOME_VISIT, WANTS_ELDER_CARE,
    WANTS_FINANCIAL_ADVICE, WANTS_CHECKUP,
    PREFERRED_SERVICES_RAW, HEALTH_CONDITIONS_RAW,
    SURVEY_SUBMITTED_DATE, CARE_NEEDS_FLAG,
    SURVEY_COMPLETENESS_SCORE, LAST_UPDATED
)
TARGET_LAG = '2 hours'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    CUSTOMER_ID, SURVEY_ID, SUBMITTED_BY,
    CONDITION_COUNT, HAS_DIABETES, HAS_HYPERTENSION, HAS_HEART_DISEASE,
    HAS_COPD, HAS_ARTHRITIS, HAS_ANY_CONDITION,
    CURRENT_COVERAGE_STATUS, IS_UNINSURED,
    LIVING_SITUATION, LIVING_ALONE_FLAG, IN_CARE_HOME_FLAG,
    WANTS_TELEMEDICINE, WANTS_HOME_VISIT, WANTS_ELDER_CARE,
    WANTS_FINANCIAL_ADVICE, WANTS_CHECKUP,
    PREFERRED_SERVICES_RAW, HEALTH_CONDITIONS_RAW,
    SURVEY_SUBMITTED_DATE,
    (LIVING_ALONE_FLAG AND HAS_ANY_CONDITION) OR IN_CARE_HOME_FLAG AS CARE_NEEDS_FLAG,
    (
        IFF(CURRENT_COVERAGE_STATUS IS NOT NULL, 1, 0) +
        IFF(LIVING_SITUATION IS NOT NULL, 1, 0) +
        IFF(HEALTH_CONDITIONS_RAW IS NOT NULL, 1, 0) +
        IFF(PREFERRED_SERVICES_RAW IS NOT NULL, 1, 0) +
        IFF(SURVEY_SUBMITTED_DATE IS NOT NULL, 1, 0)
    ) / 5.0 AS SURVEY_COMPLETENESS_SCORE,
    CURRENT_TIMESTAMP() AS LAST_UPDATED
FROM PROTECT360_DB.SILVER.SURVEY_RESPONSE;
