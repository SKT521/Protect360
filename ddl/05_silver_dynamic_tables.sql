CREATE OR REPLACE DYNAMIC TABLE PROTECT360_DB.SILVER.POLICY_SUMMARY(
    CUSTOMER_ID, ACTIVE_POLICY_COUNT, CURRENT_COVERAGE_TYPE,
    TOTAL_ANNUAL_PREMIUM, PROTECTION_GAP_FLAG, HAS_ANY_COVERAGE_FLAG,
    LAST_UPDATED
)
TARGET_LAG = '2 hours'
REFRESH_MODE = AUTO
INITIALIZE = ON_CREATE
WAREHOUSE = TRANSFORM_WH
AS
SELECT
    CUSTOMER_ID,
    COUNT(CASE WHEN STATUS = 'ACTIVE' THEN 1 END) AS ACTIVE_POLICY_COUNT,
    MAX(CASE WHEN STATUS = 'ACTIVE' THEN PRODUCT_TYPE END) AS CURRENT_COVERAGE_TYPE,
    COALESCE(SUM(
        CASE WHEN STATUS = 'ACTIVE' THEN ANNUAL_PREMIUM ELSE 0 END
    ), 0) AS TOTAL_ANNUAL_PREMIUM,
    (COUNT(CASE WHEN STATUS = 'ACTIVE' THEN 1 END) = 0)::BOOLEAN AS PROTECTION_GAP_FLAG,
    BOOLOR_AGG(STATUS = 'ACTIVE') AS HAS_ANY_COVERAGE_FLAG,
    CURRENT_TIMESTAMP() AS LAST_UPDATED
FROM PROTECT360_DB.SILVER.POLICY
GROUP BY CUSTOMER_ID;


